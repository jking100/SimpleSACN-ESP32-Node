void test_valid_packet_parses(void)
{
    sacnPacket out{};
    TEST_ASSERT_EQUAL(parseStatus::GOOD, parseToSACN(data::uni1_ch1_8_255_bytes, SACN_PACKET_SIZE, &out));
    TEST_ASSERT_EQUAL_UINT8(0x00, out.propertyValues[0]); // DMX start code
    TEST_ASSERT_EQUAL_UINT8(0xff, out.propertyValues[1]); // channel 1
    TEST_ASSERT_EQUAL_UINT8(0xff, out.propertyValues[8]); // channel 8
}

void test_valid_packet_multibyte_fields(void)
{
    // raw fields stay in network order, accessors give host order
    sacnPacket out{};
    TEST_ASSERT_EQUAL(parseStatus::GOOD, parseToSACN(data::uni1_ch1_8_255_bytes, SACN_PACKET_SIZE, &out));
    TEST_ASSERT_EQUAL_UINT16(1, universe(out));
    TEST_ASSERT_EQUAL_UINT16(513, slotCount(out));
    TEST_ASSERT_EQUAL_UINT8(100, out.priority);
    TEST_ASSERT_EQUAL_UINT8(0xc1, out.sequenceNumber);
}

void test_zero_buffer_rejected(void)
{
    unsigned char junk[SACN_PACKET_SIZE] = {0};
    sacnPacket out{};
    TEST_ASSERT_NOT_EQUAL(parseStatus::GOOD, parseToSACN(junk, SACN_PACKET_SIZE, &out));
}

void test_wrong_buffer_size_rejected(void)
{
    sacnPacket out{};
    TEST_ASSERT_EQUAL_STRING("INCORRECT_BUFFER_SIZE", parseStatus_to_string(parseToSACN(data::uni1_ch1_8_255_bytes, SACN_PACKET_SIZE - 1, &out)));
    TEST_ASSERT_EQUAL_STRING("INCORRECT_BUFFER_SIZE", parseStatus_to_string(parseToSACN(data::uni1_ch1_8_255_bytes, SACN_PACKET_SIZE + 1, &out)));
    TEST_ASSERT_EQUAL_STRING("INCORRECT_BUFFER_SIZE", parseStatus_to_string(parseToSACN(data::uni1_ch1_8_255_bytes, 0, &out)));
}

// ----------------------------------------
// one test per failure path, each one flips a single byte of the good capture

// byte offsets into the raw packet, guarded against the struct layout so they cant drift
namespace offsets
{
    constexpr size_t preamble{0};
    constexpr size_t postamble{2};
    constexpr size_t acnId{4};
    constexpr size_t rootVector{18};
    constexpr size_t framingVector{40};
    constexpr size_t startCode{125};

    static_assert(offsetof(sacnPacket, preambleSize) == preamble, "preamble offset");
    static_assert(offsetof(sacnPacket, postambleSize) == postamble, "postamble offset");
    static_assert(offsetof(sacnPacket, ACNPacketIdentifier) == acnId, "acn id offset");
    static_assert(offsetof(sacnPacket, rootVector) == rootVector, "root vector offset");
    static_assert(offsetof(sacnPacket, framingVector) == framingVector, "framing vector offset");
    static_assert(offsetof(sacnPacket, propertyValues) == startCode, "start code offset");
}

// copy the good capture, overwrite one byte, parse it
parseStatus parseMutated(size_t offset, uint8_t value)
{
    uint8_t buf[SACN_PACKET_SIZE];
    memcpy(buf, data::uni1_ch1_8_255_bytes, SACN_PACKET_SIZE);
    buf[offset] = value;

    sacnPacket out{};
    return parseToSACN(buf, SACN_PACKET_SIZE, &out);
}

void test_bad_preamble_rejected(void)
{
    // 0x0010 -> 0x0011
    TEST_ASSERT_EQUAL_STRING("FAILED_PREAMBLE", parseStatus_to_string(parseMutated(offsets::preamble + 1, 0x11)));
}

void test_bad_postamble_rejected(void)
{
    // 0x0000 -> 0x0001
    TEST_ASSERT_EQUAL_STRING("FAILED_POSTAMBLE", parseStatus_to_string(parseMutated(offsets::postamble + 1, 0x01)));
}

void test_bad_acn_id_rejected(void)
{
    // "ASC-E1.17" -> "XSC-E1.17"
    TEST_ASSERT_EQUAL_STRING("FAILED_ACN_ID", parseStatus_to_string(parseMutated(offsets::acnId, 'X')));
}

void test_bad_acn_id_trailing_null_rejected(void)
{
    // the 3 trailing nulls are part of the id too
    TEST_ASSERT_EQUAL_STRING("FAILED_ACN_ID", parseStatus_to_string(parseMutated(offsets::acnId + 11, 0x01)));
}

void test_bad_root_vector_rejected(void)
{
    // VECTOR_ROOT_E131_DATA 0x00000004 -> 0x00000008 (VECTOR_ROOT_E131_EXTENDED, sync/discovery)
    TEST_ASSERT_EQUAL_STRING("FAILED_ROOT_VECTOR", parseStatus_to_string(parseMutated(offsets::rootVector + 3, 0x08)));
}

void test_bad_framing_vector_rejected(void)
{
    // VECTOR_E131_DATA_PACKET 0x00000002 -> 0x00000001
    TEST_ASSERT_EQUAL_STRING("FAILED_FRAMING_VECTOR", parseStatus_to_string(parseMutated(offsets::framingVector + 3, 0x01)));
}

void test_nonzero_start_code_rejected(void)
{
    // 0xDD is the per-address-priority start code desks send alongside levels, anything non zero gets dropped
    TEST_ASSERT_EQUAL_STRING("FAILED_CHANNEL_START_CODE", parseStatus_to_string(parseMutated(offsets::startCode, 0xDD)));
}

void test_failed_parse_leaves_out_untouched(void)
{
    uint8_t buf[SACN_PACKET_SIZE];
    memcpy(buf, data::uni1_ch1_8_255_bytes, SACN_PACKET_SIZE);
    buf[offsets::startCode] = 0xDD; // fails on the last check, after everything else passed

    sacnPacket out{};
    memset(out.raw, 0xAA, SACN_PACKET_SIZE);

    TEST_ASSERT_NOT_EQUAL(parseStatus::GOOD, parseToSACN(buf, SACN_PACKET_SIZE, &out));
    TEST_ASSERT_EACH_EQUAL_UINT8(0xAA, out.raw, SACN_PACKET_SIZE);
}

